name = "Nyasa"

print(name[0:3]) # Output: Nya

print(name[-4:-1]) # Output: yas
print(name[1:4]) # Output: yas

print(name[:4]) #is same as name[0:4], Output: Nyas
print(name[2:]) #is same as name[2:length of the string], Output: asa
print(name[:]) #is same as name[0:length of the string], Output: Nyasa